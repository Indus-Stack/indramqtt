def check_cli_against_sources() -> None:
    """Check each documented flag against the command definitions."""
    main_src = read_text(ROOT / "crates" / "broker-node" / "src" / "main.rs")
    # Each flag of the table must occur as a field of Args.
    for flag, _kind, _default, _home, _effect in INDRA_MQTT_FLAGS:
        long = flag.split(", ")[-1].lstrip("-").replace("-", "_")
        if not re.search(rf"\b{re.escape(long)}\s*:", main_src):
            raise SystemExit(f"flag {flag} is missing from the Args struct")
    indra_src = read_text(ROOT / "crates" / "broker-node" / "src" / "indra.rs")
    # Each documented command must occur as a variant of the ctl tree.
    for command, _effect in CTL_COMMANDS:
        words = command.split()[1:]
        for word in words:
            variant = word.capitalize()
            if not re.search(rf"\b{re.escape(variant)}\b", indra_src):
                raise SystemExit(f"command {command} is missing from the ctl tree")


