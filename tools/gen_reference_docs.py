FIELD_RE = re.compile(
    r"FieldDoc\s*\{\s*"
    r'path:\s*"(?P<path>(?:[^"\\]|\\.)*)",\s*'
    r'setting_type:\s*"(?P<type>(?:[^"\\]|\\.)*)",\s*'
    r'default:\s*"(?P<default>(?:[^"\\]|\\.)*)",\s*'
    r'range:\s*"(?P<range>(?:[^"\\]|\\.)*)",\s*'
    r'doc:\s*"(?P<doc>(?:[^"\\]|\\.)*)",\s*'
    r"requires_restart:\s*(?P<restart>true|false|None),?\s*"
    r"\},",
    re.DOTALL,
)


def unescape(raw: str) -> str:
    """Unescape a Rust string literal body."""
    return json.loads('"' + raw + '"')


def load_fields() -> list:
    """Load every catalogued setting from the schema source."""
    src = read_text(ROOT / "crates" / "broker-config" / "src" / "schema.rs")
    fields = []
    for match in FIELD_RE.finditer(src):
        row = {key: unescape(match.group(key)) for key in ("path", "type", "default", "range", "doc")}
        raw = match.group("restart")
        if raw == "true":
            row["restart"] = "yes"
        elif raw == "false":
            row["restart"] = "no"
        else:
            row["restart"] = ""
        fields.append(row)
    if not fields:
        raise SystemExit("schema catalogue is empty")
    return fields


