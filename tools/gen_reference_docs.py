def load_openapi(path: str | None = None) -> dict:
    """Load the OpenAPI document that the broker serves."""
    if path:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    src = read_text(ROOT / "crates" / "broker-api" / "src" / "swagger.rs")
    match = None
    for raw in re.findall(r'r#"(.*?)"#', src, re.DOTALL):
        if raw.lstrip().startswith("{"):
            match = raw
            break
    if match is None:
        raise SystemExit("served OpenAPI document is missing from swagger.rs")
    return json.loads(match)


def slugify_tag(name: str) -> str:
    """Map a tag name to a file name."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug or "misc"


def example_path(path: str) -> str:
    """Replace path parameters with concrete example values."""
    # Copy-paste runs: values name real example objects from the flows.
    # The docs harness never runs these curl blocks (`curl` fences
    # carry no marker). The tested flow below runs the live calls.
    values = {"id": "1", "username": "doc-user-1"}

    def var(match: re.Match) -> str:
        name = match.group(0).strip("{}").lower()
        return values.get(name, "1")

    return re.sub(r"\{[^}]+\}", var, path)


def example_scalar(name: str, spec: dict):
    """Build one illustrative value from its schema entry."""
    if not isinstance(spec, dict):
        return ""
    if "example" in spec:
        return spec["example"]
    if "default" in spec:
        return spec["default"]
    enum = spec.get("enum", [])
    if isinstance(enum, list) and enum:
        return enum[0]
    kind = spec.get("type", "")
    if kind == "boolean":
        return True
    if kind == "integer":
        return 1
    if kind == "number":
        return 1
    if kind == "array":
        return []
    if kind == "object":
        return {}
    return ""


def example_body(schema: dict) -> str:
    """Build an example request body from schema types."""
    if not isinstance(schema, dict):
        return "{}"
    props = schema.get("properties", {})
    if not isinstance(props, dict) or not props:
        return "{}"
    body = {}
    for name, spec in props.items():
        if not isinstance(spec, dict):
            continue
        if "example" in spec:
            body[name] = spec["example"]
        elif "default" in spec:
            body[name] = spec["default"]
        else:
            body[name] = example_scalar(name, spec)
    if not body:
        required = schema.get("required", [])
        for name in required if isinstance(required, list) else []:
            body[name] = ""
    return json.dumps(body, indent=2)


def curl_example(method: str, path: str, op: dict) -> str:
    """Build one curl example for an operation."""
    url = "http://127.0.0.1:18083" + example_path(path)
    query = []
    for param in op.get("parameters", []) if isinstance(op.get("parameters"), list) else []:
        if not isinstance(param, dict) or param.get("in") != "query":
            continue
        schema = param.get("schema", {}) if isinstance(param.get("schema"), dict) else {}
        if "example" in schema:
            query.append(f"{param.get('name', 'q')}={schema['example']}")
        elif "default" in schema:
            query.append(f"{param.get('name', 'q')}={schema['default']}")
        # Optional query without a documented value stays out of the
        # example. Absent means the default tenant.
    if query:
        url += "?" + "&".join(query)
    # The first lines state that this block is illustrative: values
    # come from the schema above. The example flow below runs the
    # verified calls against a started broker.
    lines = [
        "# Illustrative request. Values come from the schema above.",
        "# The example flow below runs verified calls on a live broker.",
        f"curl -s -X {method.upper()} '{url}' \\",
        '  -H "Authorization: Bearer $INDRA_API_KEY"',
    ]
    body = None
    if method.lower() in ("post", "put", "patch"):
        content = (
            (op.get("requestBody", {}) if isinstance(op.get("requestBody"), dict) else {}).get(
                "content", {}
            )
            if isinstance(op.get("requestBody"), dict)
            else {}
        )
        if isinstance(content, dict) and "application/json" in content:
            media = content["application/json"]
            schema = media.get("schema", {}) if isinstance(media, dict) else {}
            body = example_body(schema)
    if body is not None:
        lines[-1] += " \\"
        lines.append('  -H "Content-Type: application/json" \\')
        lines.append(f"  -d '{body}'")
    return "\n".join(lines)


def render_parameters(op: dict) -> str:
    """Render the parameter table of an operation."""
    params = op.get("parameters", [])
    if not isinstance(params, list) or not params:
        return "No parameters.\n"
    out = ["| Name | In | Required | Type | Description |", "|---|---|---|---|---|"]
    for param in params:
        if not isinstance(param, dict):
            continue
        schema = param.get("schema", {}) if isinstance(param.get("schema"), dict) else {}
        out.append(
            f"| `{param.get('name', '')}` | {param.get('in', '')} "
            f"| {str(param.get('required', False)).lower()} "
            f"| {schema.get('type', '')} | {param.get('description', '')} |"
        )
    return "\n".join(out) + "\n"


def render_response_body(status: str, resp: dict) -> str:
    """Render one response body schema from the OpenAPI entry."""
    if not isinstance(resp, dict):
        return ""
    content = resp.get("content", {})
    if not isinstance(content, dict) or not content:
        return ""
    parts = []
    for media in sorted(content):
        entry = content[media] if isinstance(content[media], dict) else {}
        schema = entry.get("schema", {}) if isinstance(entry, dict) else {}
        parts.append(f"Media type `{media}`:")
        parts.append("")
        parts.append("```json")
        parts.append(json.dumps(schema, indent=2))
        parts.append("```")
        parts.append("")
    return "\n".join(parts)


def render_request_body(op: dict) -> str:
    """Render the request body schema of an operation."""
    body = op.get("requestBody", {})
    if not isinstance(body, dict) or not body:
        return "No request body.\n"
    content = body.get("content", {})
    if not isinstance(content, dict) or not content:
        return "No request body.\n"
    parts = []
    for media in sorted(content):
        entry = content[media] if isinstance(content[media], dict) else {}
        schema = entry.get("schema", {}) if isinstance(entry, dict) else {}
        parts.append(f"Media type `{media}`:")
        parts.append("")
        required = schema.get("required", []) if isinstance(schema, dict) else []
        if isinstance(required, list) and required:
            names = ", ".join(f"`{name}`" for name in required)
            parts.append(f"Required: {names}.")
            parts.append("")
        props = schema.get("properties", {}) if isinstance(schema, dict) else {}
        if isinstance(props, dict) and props:
            parts.append("| Field | Type | Description |")
            parts.append("|---|---|---|")
            for name, spec in props.items():
                if not isinstance(spec, dict):
                    continue
                parts.append(f"| `{name}` | {spec.get('type', '')} | {spec.get('description', '')} |")
            parts.append("")
        else:
            parts.append("```json")
            parts.append(json.dumps(schema, indent=2))
            parts.append("```")
            parts.append("")
    return "\n".join(parts) + "\n"


def render_responses(op: dict) -> str:
    """Render the response table plus each response body schema."""
    responses = op.get("responses", {})
    if not isinstance(responses, dict) or not responses:
        return "No documented responses.\n"
    out = ["| Status | Description |", "|---|---|"]
    for status in sorted(responses, key=str):
        resp = responses[status] if isinstance(responses[status], dict) else {}
        out.append(f"| {status} | {resp.get('description', '')} |")
    out.append("")
    for status in sorted(responses, key=str):
        resp = responses[status] if isinstance(responses[status], dict) else {}
        body = render_response_body(status, resp)
        if body:
            out.append(f"Response `{status}` body:")
            out.append("")
            out.append(body)
    return "\n".join(out) + "\n"


