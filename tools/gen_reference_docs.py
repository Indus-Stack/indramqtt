# No metric name is written by hand here. The names, kinds and meanings
# come from the HELP and TYPE lines in broker-observability/src/lib.rs,
# and the snapshot fields come from the MetricsSnapshot struct there.


def load_method_docs() -> dict:
    """Read one meaning per counter from the increment method docs."""
    # Each `inc_<field>` method carries a doc comment. That comment
    # is the meaning from the code that registers the metric.
    src = read_text(ROOT / "crates" / "broker-observability" / "src" / "lib.rs")
    docs = {}
    pattern = re.compile(
        r"((?:^[ \t]*///.*\n)+)^[ \t]*pub fn (inc_|set_)([A-Za-z0-9_]+)\s*\(",
        re.MULTILINE,
    )
    for match in pattern.finditer(src):
        comment, _, method = match.groups()
        text = " ".join(
            line.split("///", 1)[1].strip()
            for line in comment.strip().splitlines()
            if line.split("///", 1)[1].strip()
            and not line.split("///", 1)[1].strip().startswith("[")
        )
        first = text.split(". ")[0].strip().rstrip(".")
        if not first:
            continue
        name = method[:-3] if method.endswith("_by") else method
        if method.startswith("inc_") or not name.endswith("_by"):
            docs.setdefault("inc_" + name, first + ".")
    return docs


def metric_meaning(name: str, field: str, helps: dict, methods: dict) -> tuple:
    """Return the meaning and its source for one metric."""
    # HELP text wins for exposition names. Method docs cover the
    # snapshot fields. Nothing is invented from the field name.
    if name in helps:
        return helps[name].strip().rstrip(".") + ".", "HELP text"
    doc = methods.get("inc_" + field)
    if doc:
        return doc, "counter docs"
    return "Counted by the broker. No HELP text names it.", "unstated"


def load_metrics_from_code() -> tuple:
    """Read exposition names and snapshot fields from the metrics code."""
    src = read_text(ROOT / "crates" / "broker-observability" / "src" / "lib.rs")
    helps = dict(re.findall(r"# HELP (indramqtt_[A-Za-z0-9_]+)\s+(.*?)(?:\\n)", src))
    kinds = dict(re.findall(r"# TYPE (indramqtt_[A-Za-z0-9_]+)\s+(\w+)", src))
    methods = load_method_docs()
    names = sorted(set(re.findall(r"indramqtt_[a-z0-9_]+", src)))
    exposed = []
    for name in names:
        field = name[len("indramqtt_"):]
        if field.endswith("_total"):
            field = field[: -len("_total")]
        kind = kinds.get(name, "counter")
        if "connections_active" in name:
            unit = "connections"
        elif field.startswith("bytes"):
            unit = "bytes"
        else:
            unit = "count"
        meaning, source = metric_meaning(name, field, helps, methods)
        exposed.append((name, field, kind, unit, meaning, source))
    if not exposed:
        raise SystemExit("metrics exposition is empty")
    body = src.split("pub struct MetricsSnapshot", 1)[1].split("}", 1)[0]
    struct_fields = re.findall(r"pub (\w+)\s*:", body)
    covered = {field for _name, field, _kind, _unit, _meaning, _source in exposed}
    snapshot_only = []
    for field in struct_fields:
        if field in covered:
            continue
        if field.startswith("bytes"):
            unit = "bytes"
        else:
            unit = "count"
        doc = methods.get("inc_" + field)
        if doc:
            snapshot_only.append((field, "counter", unit, doc, "counter docs"))
        else:
            snapshot_only.append(
                (field, "counter", unit, "Counted by the broker. No HELP text names it.", "unstated")
            )
    if not snapshot_only:
        raise SystemExit("metrics snapshot is empty")
    return exposed, snapshot_only


def check_metrics_against_sources() -> None:
    """Check that the metrics code parses: names come from the code."""
    exposed, snapshot_only = load_metrics_from_code()
    if not exposed or not snapshot_only:
        raise SystemExit("metrics code gave no rows")


