def desired_files(openapi_json: str | None = None) -> dict:
    """Render every artefact. Return a map of path to content."""
    spec = load_openapi(openapi_json)
    files = {}
    for name, content in api_pages(spec).items():
        files[API_DIR / name] = content
    files[REF / "configuration.md"] = config_page(load_fields())
    files[REF / "cli.md"] = cli_page()
    files[REF / "metrics.md"] = metrics_page()
    return files


def artefact_files(artefact: str, openapi_json: str | None = None) -> dict:
    """Render one artefact only."""
    all_files = desired_files(openapi_json)
    if artefact == "api":
        return {path: text for path, text in all_files.items() if path.parent == API_DIR}
    if artefact == "config":
        return {REF / "configuration.md": all_files[REF / "configuration.md"]}
    if artefact == "cli":
        return {REF / "cli.md": all_files[REF / "cli.md"]}
    if artefact == "metrics":
        return {REF / "metrics.md": all_files[REF / "metrics.md"]}
    raise SystemExit(f"unknown artefact: {artefact}")


def main() -> int:
    """Run the generator."""
    parser = argparse.ArgumentParser(description="Generate the reference pages.")
    parser.add_argument("--write", action="store_true", help="rewrite the pages")
    parser.add_argument("--check", action="store_true", help="fail when a page drifts")
    parser.add_argument("artefact", nargs="?", default="all", help="api, config, cli or metrics")
    parser.add_argument("--openapi-json", default=None, help="use this served OpenAPI JSON instead of swagger.rs")
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.print_help()
        return 2
    files = (
        desired_files(args.openapi_json)
        if args.artefact == "all"
        else artefact_files(args.artefact, args.openapi_json)
    )
    if args.write:
        for path, content in sorted(files.items()):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        print(f"wrote {len(files)} files")
        return 0
    failures = 0
    for path in sorted(files):
        if not path.is_file():
            print(f"FAIL {path} is missing")
            failures += 1
            continue
        current = path.read_text(encoding="utf-8")
        if current != files[path]:
            print(f"FAIL {path} differs from the generator output")
            for line in difflib.unified_diff(
                current.splitlines(), files[path].splitlines(), str(path), "generated", lineterm=""
            ):
                print(line)
            failures += 1
    if failures:
        return 1
    print(f"ok {len(files)} files match the generator output")
    return 0


if __name__ == "__main__":
    sys.exit(main())
