#!/usr/bin/env python3
"""Build doc entries from inventory, text and verified output (DX-01).

Read the inventory (name, signature, types, defaults), the written
explanation (docs/_text/<area>/<item>.md) and the verified output
(docs/_verified/<area>/<item>.json). Build each entry of a page.
An item with no verified output gets the callout "Not verified:
see the failure record". Page files under docs/ are outputs of
this generator. Use --check to fail on drift, --write to rewrite.
Standard library only. Run from the workspace root:
  python3 docs/_tools/entries.py --write [--area cli]
  python3 docs/_tools/entries.py --check [--area cli]
  python3 docs/_tools/entries.py --coverage [--area cli]
Coverage prints items, verified, failed per area.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT / "tools"
INVENTORY = ROOT / "docs" / "_inventory"
TEXT = ROOT / "docs" / "_text"
VERIFIED = ROOT / "docs" / "_verified"
FAILURES = ROOT / "docs" / "_verification" / "failures.md"

sys.path.insert(0, str(TOOLS))
import gen_reference_docs as gen  # noqa: E402

GENERATED = (
    "<!-- GENERATED by `python3 docs/_tools/entries.py` "
    "from `docs/_inventory/`, `docs/_text/` and `docs/_verified/`. "
    "Do not edit by hand. -->"
)

NOT_VERIFIED = "Not verified: see `../_verification/failures.md`."


def cli_items():
    """List every CLI item id with its inventory row."""
    data = json.loads((INVENTORY / "cli.json").read_text(encoding="utf-8"))
    out = []
    for row in data["binaries"][0]["flags"]:
        long = row["flag"].split(", ")[-1].strip()
        out.append(("flag-" + long.lstrip("-"), "flag", row))
    for row in data["binaries"][1]["commands"]:
        words = row["command"].split()
        out.append(("cmd-" + "-".join(words[1:]), "command", row))
    out.append(("bin-indramqtt", "binary", {"name": "indramqtt"}))
    out.append(("bin-indra", "binary", {"name": "indra"}))
    return out


def read_text(area, item):
    """Read the written explanation of one item, or None."""
    path = TEXT / area / (item + ".md")
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return None


def read_verified(area, item):
    """Read the verified output of one item, or None."""
    path = VERIFIED / area / (item + ".json")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except OSError:
        return None


def failure_recorded(item):
    """Check whether failures.md names this item."""
    try:
        return f"DX-01 item `{item}`" in FAILURES.read_text(encoding="utf-8")
    except OSError:
        return False


def verified_line(area, item, record):
    """Build the verified-evidence line of one entry."""
    cmd = " ".join(record.get("command", []))
    cmd = cmd.replace("/work/target/debug/", "").replace("<tmp>", "/tmp/dx")
    code = record.get("returncode", "?")
    match = record.get("match", "")
    if match:
        return (
            f"Verified: `{cmd}` exits {code} and shows `{match}`. "
            f"See `../_verified/{area}/{item}.json`."
        )
    return (
        f"Verified: `{cmd}` exits {code}. "
        f"See `../_verified/{area}/{item}.json`."
    )


