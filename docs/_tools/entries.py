def area_counts(area):
    """Count items, verified and failed of one area."""
    data = json.loads((INVENTORY / (area + ".json")).read_text(encoding="utf-8"))
    if area == "cli":
        ids = [item for item, _, _ in cli_items()]
    elif area == "config":
        ids = [s["path"] for s in data["settings"]]
    elif area == "api":
        ids = [o["method"] + " " + o["path"] for o in data["operations"]]
    elif area == "mcp":
        ids = [t["name"] for t in data["tools"]]
    elif area == "rules":
        ids = [stem for _, stem in rules_inventory_ids()]
    elif area == "connectors":
        ids = [c["kind"] for c in data["connectors"]]
    elif area == "metrics":
        ids = [m["name"] for m in data["metrics"]]
    else:
        return (area, 0, 0, 0)
    verified = failed = 0
    for item in ids:
        if read_verified(area, item):
            verified += 1
        elif failure_recorded(item):
            failed += 1
    # Entries for wave DX2 areas live under docs/ pages, not per-item
    # files yet. Count them as pending, not failed, outside cli.
    return (area, len(ids), verified, failed)


def coverage(area=""):
    """Print items, verified, failed for every area or one."""
    areas = [area] if area else ["cli", "config", "api", "mcp", "rules", "connectors", "metrics"]
    code = 0
    for name in areas:
        _, items, verified, failed = area_counts(name)
        missing = items - verified - failed
        print(f"area={name} items={items} verified={verified} failed={failed}")
        if name == "cli" and missing:
            print(f"coverage: cli misses {missing} items")
            code = 1
        if name == "rules":
            claimed_missing = 0
            for label, stem in rules_inventory_ids():
                if read_text(name, stem) is None:
                    continue
                if read_verified(name, stem):
                    print(f"item={stem} verified")
                elif failure_recorded(stem):
                    print(f"item={stem} failed")
                else:
                    print(f"item={stem} missing")
                    claimed_missing += 1
            if claimed_missing:
                print(f"coverage: rules misses {claimed_missing} claimed items")
                code = 1
    return code


