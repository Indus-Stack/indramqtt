def area_counts(area):
    """Count items, verified and failed of one area."""
    data = json.loads((INVENTORY / (area + ".json")).read_text(encoding="utf-8"))
    if area == "cli":
        ids = [item for item, _, _ in cli_items()]
    elif area == "config":
        ids = [s["path"] for s in data["settings"]]
    elif area == "api":
        ids = [o["method"] + " " + o["path"] for o in data["operations"]]
    elif area == "mcp":
        ids = [t["name"] for t in data["tools"]]
    elif area == "rules":
        ids = (
            ["fn:" + f["name"] for f in data["functions"]]
            + ["clause:" + c for c in data["clauses"]]
            + ["op:" + o for o in data["operators"]]
            + ["action:" + a for a in data["actions"]]
            + ["event:" + e for e in data["events"]]
        )
    elif area == "connectors":
        ids = [c["kind"] for c in data["connectors"]]
    elif area == "metrics":
        ids = [m["name"] for m in data["metrics"]]
    else:
        return (area, 0, 0, 0)
    verified = failed = 0
    for item in ids:
        if read_verified(area, item):
            verified += 1
        elif failure_recorded(item):
            failed += 1
    # Entries for wave DX2 areas live under docs/ pages, not per-item
    # files yet. Count them as pending, not failed, outside cli.
    return (area, len(ids), verified, failed)


def coverage(area=""):
    """Print items, verified, failed for every area or one."""
    areas = [area] if area else ["cli", "config", "api", "mcp", "rules", "connectors", "metrics"]
    code = 0
    for name in areas:
        _, items, verified, failed = area_counts(name)
        missing = items - verified - failed
        print(f"area={name} items={items} verified={verified} failed={failed}")
        if name == "cli" and missing:
            print(f"coverage: cli misses {missing} items")
            code = 1
    return code


def main(argv):
    """Run the entry generator. --write stores. --check diffs."""
    parser = argparse.ArgumentParser(description="Build doc entries.")
    parser.add_argument("--write", action="store_true", help="rewrite pages")
    parser.add_argument("--check", action="store_true", help="fail on drift")
    parser.add_argument("--coverage", action="store_true", help="print counts")
    parser.add_argument("--area", default="cli", help="one area only")
    args = parser.parse_args(argv)
    if args.coverage:
        return coverage("" if args.area == "all" else args.area)
    if args.area != "cli":
        print("wave DX2 owns every area except cli")
        return 2
    fresh = render_cli_page()
    path = ROOT / "docs" / "reference" / "cli.md"
    if args.write:
        path.write_text(fresh, encoding="utf-8")
        print(f"wrote {path}")
        return 0
    if args.check:
        have = path.read_text(encoding="utf-8")
        if have != fresh:
            print("drift: docs/reference/cli.md differs: run --write")
            return 1
        print("entries match: docs/reference/cli.md")
        return 0
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
