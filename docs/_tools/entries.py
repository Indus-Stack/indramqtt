def cli_items():
    """List every CLI item id with its inventory row."""
    data = json.loads((INVENTORY / "cli.json").read_text(encoding="utf-8"))
    out = []
    for row in data["binaries"][0]["flags"]:
        long = row["flag"].split(", ")[-1].strip()
        out.append(("flag-" + long.lstrip("-"), "flag", row))
    for row in data["binaries"][1]["commands"]:
        words = row["command"].split()
        out.append(("cmd-" + "-".join(words[1:]), "command", row))
    out.append(("bin-indramqtt", "binary", {"name": "indramqtt"}))
    out.append(("bin-indra", "binary", {"name": "indra"}))
    return out


def read_text(area, item):
    """Read the written explanation of one item, or None."""
    path = TEXT / area / (item + ".md")
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return None


def read_verified(area, item):
    """Read the verified output of one item, or None."""
    path = VERIFIED / area / (item + ".json")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except OSError:
        return None


def failure_recorded(item):
    """Check whether failures.md names this item."""
    try:
        text = FAILURES.read_text(encoding="utf-8")
    except OSError:
        return False
    return f"item `{item}`" in text


def verified_line(area, item, record):
    """Build the verified-evidence line of one entry."""
    cmd = " ".join(record.get("command", []))
    cmd = cmd.replace("/work/target/debug/", "").replace("<tmp>", "/tmp/dx")
    code = record.get("returncode", "?")
    match = record.get("match", "")
    if match:
        return (
            f"Verified: `{cmd}` exits {code} and shows `{match}`. "
            f"See `../_verified/{area}/{item}.json`."
        )
    return (
        f"Verified: `{cmd}` exits {code}. "
        f"See `../_verified/{area}/{item}.json`."
    )


