//! Records the compiler release and the target of this build.
//!
//! `GET /nodes` reports them in the `otp_release` field. The reference API
//! uses that field for the Erlang release. This node has no Erlang runtime,
//! so the field carries the Rust compiler release and the target triple.
//! The script runs only at build time and adds no dependency.
//!
//! The script also emits the MCP route table (`mcp_tool_table.rs`): one
//! row per `(method, path)` pair scanned out of the router source with
//! the shared scanner in `src/mcp/route_scan.rs`. The MCP tool list and
//! the coverage test both read this table, so the tools track the HTTP
//! routes with no hand-written copy. A tool description keeps the first
//! doc-comment line of its handler and names the route after it
//! (`METHOD path` in parentheses); a route without docs falls back to
//! `METHOD path`. The script never fails a row: a missing file or a
//! missing doc comment gives the fallback text.

include!("src/mcp/route_scan.rs");

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
    // `rustc --version` prints `rustc 1.88.0 (hash date)`. Keep the release.
    let release = Command::new(rustc)
        .arg("--version")
        .output()
        .ok()
        .and_then(|out| String::from_utf8(out.stdout).ok())
        .and_then(|text| text.split_whitespace().nth(1).map(str::to_string))
        .unwrap_or_default();
    let target = std::env::var("TARGET").unwrap_or_default();
    println!("cargo:rustc-env=INDRA_BUILD_RUSTC={release}");
    println!("cargo:rustc-env=INDRA_BUILD_TARGET={target}");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=RUSTC");
    println!("cargo:rerun-if-env-changed=TARGET");
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=src/v5/mod.rs");
    println!("cargo:rerun-if-changed=src/mcp/route_scan.rs");
    emit_mcp_tool_table();
}

/// Scan the router source and write the MCP route table.
fn emit_mcp_tool_table() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let v5_mod = read_file(&manifest.join("src/v5/mod.rs"));
    let lib = read_file(&manifest.join("src/lib.rs"));
    let mut routes = scan_routes(&v5_mod, "/api/v5");
    for route in scan_routes(&lib, "") {
        routes.push(route);
    }
    routes.sort_by(|a, b| (&a.path, &a.method).cmp(&(&b.path, &b.method)));
    routes.dedup_by(|a, b| a.path == b.path && a.method == b.method);
    let mut table = String::new();
    table.push_str("// One scanned HTTP operation: method, path, tool name, summary.\n");
    table.push_str("// Generated by `build.rs` out of the router source. Do not edit.\n");
    table.push_str("pub struct McpRouteEntry {\n");
    table.push_str("    pub method: &'static str,\n");
    table.push_str("    pub path: &'static str,\n");
    table.push_str("    pub tool: &'static str,\n");
    table.push_str("    pub summary: &'static str,\n");
    table.push_str("}\n");
    table.push_str("// Every `(method, path)` pair of the management router.\n");
    table.push_str("pub const MCP_ROUTE_TABLE: &[McpRouteEntry] = &[\n");
    for route in &routes {
        let from_v5 = route.path.starts_with("/api/v5/");
        let router_src = if from_v5 { &v5_mod } else { &lib };
        let tool = tool_name_for(&route.method, &route.path);
        let summary = describe_route(&manifest, route, router_src, from_v5);
        table.push_str("    McpRouteEntry { ");
        table.push_str(&format!(
            "method: \"{}\", path: \"{}\", tool: \"{}\", summary: \"{}\"",
            escape_rust_str(&route.method),
            escape_rust_str(&route.path),
            escape_rust_str(&tool),
            escape_rust_str(&summary),
        ));
        table.push_str(" },\n");
    }
    table.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("mcp_tool_table.rs");
    if let Err(error) = std::fs::write(&out, table) {
        println!("cargo:warning=mcp tool table not written: {error}");
    }
}

/// Tool description: the handler doc line plus the route
/// (`METHOD path` in parentheses), else `METHOD path` alone. The
/// route name is added to the purpose, never used in its place.
fn describe_route(
    manifest: &Path,
    route: &ScannedRoute,
    router_src: &str,
    from_v5: bool,
) -> String {
    if !route.handler.is_empty() {
        let (file, name) = split_handler(&route.handler, from_v5);
        let content = if file == "__router__" {
            router_src.to_string()
        } else {
            read_file(&manifest.join(&file))
        };
        if !content.is_empty() {
            if let Some(summary) = find_doc_summary(&content, &name) {
                if !summary.is_empty() {
                    return format!("{summary} ({} {})", route.method, route.path);
                }
            }
        }
    }
    format!("{} {}", route.method, route.path)
}

/// Source file and function name for a dotted handler path.
///
/// A leading `v5::` segment points under `src/v5/`; any other leading
/// module of a `src/v5/mod.rs` route points under `src/v5/` too, while
/// a leading module of a `src/lib.rs` route points under `src/` (for
/// example `config_runtime::validate_config`). A bare name resolves
/// against the router file itself (`__router__`).
fn split_handler(handler: &str, from_v5: bool) -> (String, String) {
    let mut parts: Vec<&str> = handler.split("::").collect();
    let name = parts.pop().unwrap_or_default().to_string();
    let mut parts: Vec<&str> = parts.into_iter().filter(|part| *part != "crate").collect();
    if parts.first() == Some(&"v5") {
        parts.remove(0);
        return (format!("src/v5/{}.rs", parts.join("/")), name);
    }
    if parts.is_empty() {
        return (String::from("__router__"), name);
    }
    if from_v5 {
        (format!("src/v5/{}.rs", parts.join("/")), name)
    } else {
        (format!("src/{}.rs", parts.join("/")), name)
    }
}

/// Read a file to a string. Returns empty on any error; the caller
/// falls back to a generic description.
fn read_file(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_default()
}
